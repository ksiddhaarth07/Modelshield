/**
 * Regenerates src/data/tickets.ts from eval/dataset_100_tickets.json so the
 * deck and the benchmark can never drift apart.
 *
 * Usage: npm run sync:tickets
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const datasetPath = resolve(repoRoot, "eval", "dataset_100_tickets.json");
const outputPath = resolve(here, "..", "src", "data", "tickets.ts");

const dataset = JSON.parse(readFileSync(datasetPath, "utf8"));
const tickets = dataset.tickets;

const rows = tickets
  .map((ticket) => {
    const id = JSON.stringify(ticket.ticket_id);
    const subject = JSON.stringify(ticket.subject);
    const body = JSON.stringify(ticket.body);
    const severity = JSON.stringify(ticket.ground_truth.severity);
    const category = JSON.stringify(ticket.ground_truth.category);
    return `  {\n    ticket_id: ${id},\n    subject: ${subject},\n    body: ${body},\n    ground_truth: { severity: ${severity}, category: ${category} },\n  },`;
  })
  .join("\n");

const file = `// Generated by scripts/sync-tickets.mjs from eval/dataset_100_tickets.json.
// Do not edit by hand; run \`npm run sync:tickets\`.
import type { Ticket } from "../lib/types";

export const TICKETS: Ticket[] = [
${rows}
];
`;

writeFileSync(outputPath, file, "utf8");
console.log(`Wrote ${tickets.length} tickets to ${outputPath}`);
